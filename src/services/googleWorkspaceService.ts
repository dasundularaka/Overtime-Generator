import { GoogleAuthProvider, signInWithPopup, onAuthStateChanged, User } from 'firebase/auth';
import { auth, googleProvider } from '../firebase/config';

// In-memory token cache as required by workspace-integration guidelines
let cachedAccessToken: string | null = null;
let isSigningIn = false;

// Clear cached token if user signs out
if (typeof window !== 'undefined') {
  onAuthStateChanged(auth, (user) => {
    if (!user) {
      cachedAccessToken = null;
    }
  });
}

/**
 * Sets or caches the Google Workspace access token in memory.
 */
export function setCachedGoogleToken(token: string | null): void {
  cachedAccessToken = token;
}

/**
 * Returns the current cached Google Workspace access token.
 */
export function getCachedGoogleToken(): string | null {
  return cachedAccessToken;
}

/**
 * Checks whether an active Google access token is available.
 */
export function hasGoogleWorkspaceToken(): boolean {
  return !!cachedAccessToken;
}

/**
 * Acquires a Google Workspace OAuth Access Token using popup sign-in.
 */
export async function connectGoogleWorkspace(): Promise<{ user: User; accessToken: string }> {
  if (isSigningIn) {
    throw new Error('Google authentication is already in progress.');
  }

  try {
    isSigningIn = true;
    const result = await signInWithPopup(auth, googleProvider);
    const credential = GoogleAuthProvider.credentialFromResult(result);
    if (!credential?.accessToken) {
      throw new Error('Could not retrieve access token from Google.');
    }
    cachedAccessToken = credential.accessToken;
    return { user: result.user, accessToken: cachedAccessToken };
  } catch (error: any) {
    console.error('Google Workspace connection error:', error);
    throw error;
  } finally {
    isSigningIn = false;
  }
}

/**
 * Ensures a valid Google access token is available, or initiates popup connection.
 */
export async function ensureGoogleAccessToken(): Promise<string> {
  if (cachedAccessToken) {
    return cachedAccessToken;
  }
  const result = await connectGoogleWorkspace();
  return result.accessToken;
}

export interface GoogleDriveUploadResult {
  fileId: string;
  name: string;
  previewUrl: string;
  webViewLink: string;
  webContentLink?: string;
}

/**
 * Uploads a generated claim PDF report to Google Drive and configures previewing.
 */
export async function uploadClaimPdfToGoogleDrive(
  pdfBlob: Blob,
  filename: string,
  title?: string
): Promise<GoogleDriveUploadResult> {
  const token = await ensureGoogleAccessToken();

  const boundary = `-------314159265358979323846_${Date.now()}`;
  const delimiter = `\r\n--${boundary}\r\n`;
  const closeDelimiter = `\r\n--${boundary}--`;

  const metadata = JSON.stringify({
    name: filename,
    mimeType: 'application/pdf',
    description: title || 'Official Overtime Claim Form generated by Overtime Claim System',
  });

  const metadataPart = `${delimiter}Content-Type: application/json; charset=UTF-8\r\n\r\n${metadata}\r\n`;
  const fileHeader = `${delimiter}Content-Type: application/pdf\r\n\r\n`;

  const multipartBlob = new Blob(
    [metadataPart, fileHeader, pdfBlob, closeDelimiter],
    { type: `multipart/related; boundary=${boundary}` }
  );

  // 1. Upload file to Google Drive
  const uploadResponse = await fetch(
    'https://www.googleapis.com/upload/drive/v3/files?uploadType=multipart&fields=id,name,webViewLink,webContentLink',
    {
      method: 'POST',
      headers: {
        Authorization: `Bearer ${token}`,
        'Content-Type': `multipart/related; boundary=${boundary}`,
      },
      body: multipartBlob,
    }
  );

  if (!uploadResponse.ok) {
    const errorText = await uploadResponse.text();
    let friendlyMessage = `Google Drive upload failed (${uploadResponse.status})`;
    try {
      const parsed = JSON.parse(errorText);
      if (parsed.error?.message) {
        if (
          parsed.error.message.includes('has not been used in project') ||
          parsed.error.message.includes('disabled') ||
          parsed.error.code === 403 ||
          parsed.error.status === 'PERMISSION_DENIED'
        ) {
          friendlyMessage = 'Preview through Google Drive is supported for self-registered Google accounts with Google Drive API enabled. Standard built-in PDF viewer is active.';
        } else {
          friendlyMessage = parsed.error.message;
        }
      }
    } catch {
      friendlyMessage = `${friendlyMessage}: ${errorText.slice(0, 160)}`;
    }
    throw new Error(friendlyMessage);
  }

  const uploadData = await uploadResponse.json();
  const fileId = uploadData.id;

  // 2. Grant view permission so the preview iframe can render in-site without cookie blocking
  try {
    await fetch(`https://www.googleapis.com/drive/v3/files/${fileId}/permissions`, {
      method: 'POST',
      headers: {
        Authorization: `Bearer ${token}`,
        'Content-Type': 'application/json',
      },
      body: JSON.stringify({
        role: 'reader',
        type: 'anyone',
      }),
    });
  } catch (permErr) {
    console.warn('Could not set public preview permission on Drive file:', permErr);
  }

  const previewUrl = `https://drive.google.com/file/d/${fileId}/preview`;
  const webViewLink = uploadData.webViewLink || `https://drive.google.com/file/d/${fileId}/view`;

  return {
    fileId,
    name: uploadData.name || filename,
    previewUrl,
    webViewLink,
    webContentLink: uploadData.webContentLink,
  };
}

export interface WelcomeEmailDispatchPayload {
  to: string;
  name: string;
  pfNumber: string;
  initialPassword?: string;
  loginUrl?: string;
  senderName?: string;
}

/**
 * Dispatches a welcome email with credentials to a user directly via the Gmail API.
 * Uses "OT Claim" as the sender branding.
 */
export async function sendWelcomeEmailViaGmail(
  payload: WelcomeEmailDispatchPayload
): Promise<{ success: boolean; messageId?: string; error?: string }> {
  const token = await ensureGoogleAccessToken();

  const cleanPf = payload.pfNumber.trim().toUpperCase();
  const pass = payload.initialPassword || cleanPf;
  const webLink = payload.loginUrl || 'https://otclaim.vercel.app/';
  const recipient = payload.to.trim();
  const subject = `OT Claim - Your Login Credentials [${cleanPf}]`;

  const bodyText = `Dear ${payload.name || 'Staff Member'},

Welcome to OT Claim - Overtime Claim Management System.

Your user account has been successfully created by the System Administrator. You can now access the system using your PF Number credentials:

• Username (PF No): ${cleanPf}
• Initial Password: ${pass}
• System Link: ${webLink}

First-Time Login Security Notice:
For security purposes, when you log into the system for the first time, you will be prompted to set your new personal password before accessing your account dashboard.

If you have any questions or require assistance, please contact your system administrator.

Best regards,
OT Claim
Overtime Claim Management Team`;

  // Encode subject to UTF-8 RFC 2047
  const utf8Subject = `=?utf-8?B?${btoa(unescape(encodeURIComponent(subject)))}?=`;

  const emailLines = [
    'From: "OT Claim" <me>',
    `To: ${recipient}`,
    `Subject: ${utf8Subject}`,
    'MIME-Version: 1.0',
    'Content-Type: text/plain; charset=UTF-8',
    'Content-Transfer-Encoding: 7bit',
    '',
    bodyText,
  ].join('\r\n');

  // Convert to Base64url (RFC 4648 §5)
  const base64UrlMessage = btoa(unescape(encodeURIComponent(emailLines)))
    .replace(/\+/g, '-')
    .replace(/\//g, '_')
    .replace(/=+$/, '');

  const sendResponse = await fetch('https://gmail.googleapis.com/gmail/v1/users/me/messages/send', {
    method: 'POST',
    headers: {
      Authorization: `Bearer ${token}`,
      'Content-Type': 'application/json',
    },
    body: JSON.stringify({
      raw: base64UrlMessage,
    }),
  });

  if (!sendResponse.ok) {
    const errText = await sendResponse.text();
    throw new Error(`Gmail API dispatch failed (${sendResponse.status}): ${errText}`);
  }

  const sendData = await sendResponse.json();
  return {
    success: true,
    messageId: sendData.id,
  };
}
